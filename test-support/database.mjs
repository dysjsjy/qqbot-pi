import {PGlite} from '@electric-sql/pglite';
import {vector} from '@electric-sql/pglite-pgvector';
import {PGLiteSocketServer} from '@electric-sql/pglite-socket';
import {readFile,readdir} from 'node:fs/promises';
const db=await PGlite.create({extensions:{vector}});
const migrations=new URL('../src/main/resources/db/migration/',import.meta.url);
for(const file of (await readdir(migrations)).filter(f=>f.endsWith('.sql')).sort())await db.exec(await readFile(new URL(file,migrations),'utf8'));
const server=new PGLiteSocketServer({db,port:55432,host:'127.0.0.1',maxConnections:10});
await server.start();
console.log('Test PostgreSQL protocol + pgvector listening on 127.0.0.1:55432');
process.on('SIGINT',async()=>{await server.stop();await db.close();process.exit(0);});
